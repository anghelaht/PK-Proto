const assert = require('node:assert/strict');
const { createPolicyStore } = require('../workflow-policy.js');
const data = new Map();
const storage = { getItem: key => data.get(key), setItem: (key, value) => data.set(key, value) };
const definitions = {
  program: [{ key: 'context', label: 'Install context', type: 'select', options: ['System', 'User'] }, { key: 'timeout', label: 'Timeout', type: 'select', options: ['60 minutes', '90 minutes'] }],
  wrapper: [{ key: 'wrapper', label: 'Wrapper', type: 'select', options: ['PSAppDeployToolkit v4', 'Direct installer'] }]
};
const nodes = [{ id: 'program', label: 'Program', required: true }, { id: 'wrapper', label: 'Wrapper', required: false }];
const catalog = [{ name: 'Contoso Finance Tools', version: '1', publisher: 'Contoso' }];
const app = catalog[0].name;
const store = createPolicyStore(storage);
const values = store.register(definitions, nodes, catalog);
store.ensureVersion(app, '1');
store.ensureVersion(app, '2');
assert.equal(store.setOverride(app, '1', 'program.context', 'System', 'version', 'No change'), false);
assert.equal(store.effective(app, '1').values['program.context'].source, 'workflow');
store.setOverride(app, '1', 'program.context', 'User', 'version', 'User-based installer');
assert.equal(store.effective(app, '1').values['program.context'].source, 'version');
assert.equal(store.effective(app, '2').values['program.context'].value, 'System');
assert.equal(store.effective(app, '1').values['program.timeout'].source, 'workflow');
store.setOverride(app, null, 'program.timeout', '90 minutes', 'application', 'Long installer');
assert.equal(store.effective(app, '2').values['program.timeout'].value, '60 minutes');
assert.equal(store.effective(app, '3').values['program.timeout'].value, '90 minutes');
store.restore(app, '1', 'program.context');
assert.equal(store.effective(app, '1').values['program.context'].source, 'workflow');
store.setOverride(app, '1', 'program.context', 'User', 'version', 'Exception');
store.setOverride(app, '1', 'program.context', 'System', 'version', 'Keep explicit ownership');
assert.equal(store.effective(app, '1').values['program.context'].source, 'version');
store.saveInputs(app, '1', { package: 'first.msi' });
const preview = store.preview(app, '1');
store.saveInputs(app, '1', { package: 'second.msi' });
assert.equal(store.state().previews[0].inputs.package, 'first.msi');
const configuration = { program: { context: 'User' } };
store.saveDraft('guided', { configuration, optionalIds: ['wrapper'], values: values(['wrapper'], configuration) });
store.publish('guided');
assert.equal(store.effective(app, '1').binding.revision, '1.4');
assert.throws(() => store.adopt(app, '1', '1.5', false), /Review/);
store.adopt(app, '1', '1.5', true);
assert.equal(store.effective(app, '1').values['program.context'].value, 'System');
assert.equal(preview.binding.revision, '1.4');
store.setOverride(app, '1', 'wrapper.wrapper', 'Direct installer', 'version', 'No wrapper needed');
store.saveDraft('guided', { configuration: {}, optionalIds: [], values: values([], {}) });
store.publish('guided');
assert.throws(() => store.adopt(app, '1', '1.6', true), /incompatible/);
store.adopt(app, '1', '1.6', true, ['wrapper.wrapper']);
assert(!('wrapper.wrapper' in store.effective(app, '1').values));
assert.throws(() => store.setOverride(app, '1', 'program.context', 'Root', 'version', 'Invalid'), /supported/);
assert.throws(() => store.setOverride(app, '1', 'program.context', 'User', 'version', ''), /reason/);
store.detach(app);
assert.equal(store.effective(app, null).binding, null);
assert.equal(store.effective(app, '1').binding.revision, '1.6');
store.ensureVersion(app, 'local');
store.bind(app, 'starter');
assert.equal(store.effective(app, 'local').binding, null);
store.attachVersion(app, 'local');
assert.equal(store.effective(app, 'local').binding.workflowId, 'starter');
assert.throws(() => store.attachVersion(app, '1'), /already/);
const reloaded = createPolicyStore(storage);
reloaded.register(definitions, nodes, catalog);
assert.deepEqual(reloaded.state(), store.state());
console.log('PASS: narrow ownership, no-op, scopes, restore, pinning, conflicts, snapshots, persistence and detach');
